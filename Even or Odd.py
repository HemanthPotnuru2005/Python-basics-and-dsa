# Read an integer. Print whether it is even or odd, and also whether it is positive, negative or zero.


Number = int(input("Enter a number :"))

if Number == 0:
    print("the number entered is 0 ")
elif Number %2 == 0:
    print("the number is an even number ")
else : 
    print("The number is a odd number ")

if Number > 0:
    print("the number is zero ")
elif Number > 0:
    print('the number is positive ')
else : 
    print("the number is negative ")

